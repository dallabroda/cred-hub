_CAMEL = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")


def humanize(key: str) -> str:
	"""`quantidadeInstituicoes` / `quantidade_instituicoes` -> "Quantidade instituições"."""
	text = re.sub(r"[_\-]+", " ", str(key))
	words = _CAMEL.sub(" ", text).split()
	words = [WORDS.get(word.lower(), word.lower()) for word in words]
	phrase = " ".join(words)
	return phrase[:1].upper() + phrase[1:] if phrase else str(key)


def label_for(key: str) -> tuple[str, bool]:
	"""(nome para mostrar, True se veio da tabela de traduções). Chave de lista (`[0]`) não é traduzida."""
	known = KEY_LABELS.get(str(key).lower())
	if known:
		return known, True
	return humanize(key), False
